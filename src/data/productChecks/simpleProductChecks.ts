function severityRules(
  confirmed: "green" | "yellow" | "red",
  missing: "not_confirmed" | "unknown" | "not_detected" = "not_confirmed",
) {
  return [
    { status: "confirmed", severity: confirmed },
    { status: "likely", severity: confirmed },
    { status: "possible", severity: confirmed },
    { status: "lab_confirmed", severity: confirmed },
    { status: "above_limit", severity: "red" },
    { status: "not_detected", severity: "green" },
    { status: missing, severity: "green" },
    { status: "unknown", severity: "green" },
  ] satisfies ProductCheckItem["severityRules"];
}

